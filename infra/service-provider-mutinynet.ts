// The service provider's one-time wiring on Mutinynet (PASSBOOK_SP_NETWORK=mutinynet in
// infra/service-provider.sh; docs/SERVICE-PROVIDER.md "The provider on Mutinynet").
// Idempotent: a second run keeps the keys and rewrites the config.
//
//  1. keys (0600): the platform's own key ($PASSBOOK_SP_STATE/wallets/platform/secret, fresh, kept: never the
//     publicly derivable demo key on a public network), the check node's operator key (fresh, kept), and the
//     chain-check signer the running local signed stack trusts;
//  2. $PASSBOOK_SP_STATE/mutinynet.config.yaml: ONE deployment config for the platform and the
//     check node: the Mutinynet profile (KaleidoSwap Esplora, indexer and RGB proxy, the public
//     relays), the local signed scorer (ids from the running stack's api.json), the test asset.
// No chain of ours, no RGB Lightning node and no laptop lender: the lender is a phone.
// Prints one JSON line: the asset, the config path, the key files.

import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { bytesToHex, keyPairFromLabel, randomKeyPair } from '../src/core/crypto.js'
import { loadConfig } from '../src/core/config.js'
import { loadPlatformKey } from '../src/wallet/platform-key.js'

const env = (k: string) => { const v = process.env[k]; if (!v) throw new Error(`${k} is not set (run through infra/service-provider.sh)`); return v }
const PROFILE = resolve(process.env.PASSBOOK_SP_MUTINYNET_PROFILE ?? 'infra/passbook.config.mutinynet.yaml')
/** Add-on 4's Mutinynet test asset ("Passbook test USDT (mutinynet, no value)"), issued by its run's lender wallet. */
/** The end game's fresh asset ($STATE/asset.json, from infra/public-mutinynet-persona.ts plan) when present, else the 17 Oct one. */
const assetState = (state: string) => resolve(process.env.PASSBOOK_SP_MUTINYNET_STATE ?? (existsSync(join(state, 'asset.json')) ? join(state, 'asset.json') : 'data/mutinynet/state.json'))

function secretFile(STATE: string, name: string, make: () => Uint8Array, label: string): string {
  const dir = join(STATE, 'keys')
  mkdirSync(dir, { recursive: true, mode: 0o700 })
  const file = join(dir, `${name}.secret`)
  if (!existsSync(file)) {
    writeFileSync(file, `${bytesToHex(make())}\n`, { mode: 0o600 })
    writeFileSync(join(dir, `${name}.label`), `${label}\n`)
  }
  chmodSync(file, 0o600)
  return file
}

/** The deployment config: the Mutinynet profile's network, endpoints, economics and policy, with the local signed scorer. */
export function mutinynetProviderConfig(x: { profile: string; relays: string[]; assetState: string; approvedBuilds: string }): string {
  const p = loadConfig(x.profile, { checkFiles: false })
  if (p.network.name !== 'mutinynet') throw new Error(`${x.profile} is a ${p.network.name} profile, not mutinynet`)
  const e = p.economics
  const ltv = Object.entries(e.max_ltv_bps_by_term).map(([k, v]) => `${k}: ${v}`).join(', ')
  return [
    '# Generated by infra/service-provider-mutinynet.ts: the provider on Mutinynet (test coins only, labelled "mutinynet").',
    '# One deployment config for the platform and the check node. local signed or nothing: no fallback scorer.',
    'network: mutinynet',
    'endpoints:',
    `  esplora: ${p.network.endpoints.esplora}`,
    `  rgb_indexer: ${p.network.endpoints.rgb_indexer}`,
    `  rgb_proxy: ${p.network.endpoints.rgb_proxy}`,
    `  nostr: [${x.relays.join(', ')}]`,
    '',
    'scorer:',
    '  provider: in-process',
    '  fallback: none',
    '  min_trust_for_lenders: dev-inprocess',
    `  approved_builds: ${x.approvedBuilds}`,
    '',
    'settlement:',
    '  default: cosign-rgb',
    '  enabled: [cosign-rgb]',
    '',
    'negotiation:',
    '  enabled: true',
    `  max_rounds: ${p.negotiation.max_rounds}`,
    '',
    'compliance:',
    '  identity: none',
    '  sanctions: none',
    '  consent_receipts: required',
    `  approvals: { maker_checker_above_usdt: ${p.compliance.approvals.maker_checker_above_micro / 1_000_000} }`,
    '  data_retention_days: 0',
    '',
    'asset:',
    `  id_from: ${x.assetState}`,
    '',
    'economics:',
    `  platform_share_bps: ${e.platform_share_bps}`,
    `  max_apr_bps: ${e.max_apr_bps}`,
    `  max_ltv_bps_by_term: { ${ltv} }`,
    `  day_count: '${e.day_count}'`,
    `  blocks_per_day: ${e.blocks_per_day}`,
    `  fee_grace_blocks: ${e.fee_grace_blocks}`,
    '',
  ].join('\n')
}

async function main() {
  const STATE = resolve(env('PASSBOOK_SP_STATE'))
  const platform = loadPlatformKey({ dir: join(STATE, 'wallets'), create: true })!
  const operatorFile = secretFile(STATE, 'operator', () => randomKeyPair().secretKey, 'check node operator key (fresh, kept on this laptop; mutinynet)')
  // The running local signed stack trusts this chain-check signer (CHAIN_SIGNER, a publicly derivable demo key). On a public
  // network that is a labelled limitation: a real deployment needs its own key and a local signed stack that trusts it.
  const chainCheckFile = secretFile(STATE, 'chain-check', () => keyPairFromLabel('passbook-chain-observer').secretKey, 'passbook-chain-observer: publicly derivable DEMO key the local local signed stack trusts for chain checks (a labelled limitation on mutinynet)')
  const ASSET_STATE = assetState(STATE)
  const asset = JSON.parse(readFileSync(ASSET_STATE, 'utf8')) as { network: string; asset: { id: string; ticker: string; name: string } }
  if (asset.network !== 'mutinynet') throw new Error(`${ASSET_STATE} is not the Mutinynet asset`)
  const relays = env('PASSBOOK_SP_PUBLIC_RELAYS_LIST').split(',').filter(Boolean)
  const config = join(STATE, 'mutinynet.config.yaml')
  writeFileSync(config, mutinynetProviderConfig({ profile: PROFILE, relays, assetState: ASSET_STATE, approvedBuilds: resolve('infra/scorer-releases.json') }))
  loadConfig(config, { checkFiles: true }) // refuse now, not in the platform, if the config is invalid
  const prof = loadConfig(PROFILE, { checkFiles: false }).network
  const out = { v: 1, network: 'mutinynet', platform_pk: platform.pubkey, endpoints: { esplora: prof.endpoints.esplora, rgb_indexer: prof.endpoints.rgb_indexer, rgb_proxy: prof.endpoints.rgb_proxy, rgb_network: prof.rgbNetwork }, asset: { id: asset.asset.id, ticker: asset.asset.ticker, name: asset.asset.name, label: 'test USDT (mutinynet)' }, config, operator_secret_file: operatorFile, chain_check_secret_file: chainCheckFile }
  writeFileSync(join(STATE, 'mutinynet.json'), `${JSON.stringify(out, null, 2)}\n`)
  console.log(JSON.stringify(out))
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch((err) => { console.error(`service-provider mutinynet setup: ${(err as Error).message}`); process.exit(1) })
